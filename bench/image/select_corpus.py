#!/usr/bin/env python3
"""Regenerates corpus.txt from an extracted QOI benchmark suite.

    python3 select_corpus.py DIR/images > corpus.txt

For each category, the PNG files no larger than the category's pixel cap
are sorted by name (byte order); with n eligible files and a target of c,
files 0, s, 2s, ... (s = n // c) are taken until c are chosen.
"""
import hashlib
import os
import struct
import sys

# category: (target count, pixel cap in megapixels)
PLAN = {
    "photo_kodak": (24, 1.0),
    "photo_tecnick": (7, 4.2),
    "photo_wikipedia": (7, 4.2),
    "pngimg": (10, 4.2),
    "screenshot_game": (10, 4.2),
    "screenshot_web": (3, 7.0),
    "textures_photo": (4, 4.2),
    "textures_pk": (6, 4.2),
    "textures_pk01": (4, 4.2),
    "textures_pk02": (4, 4.2),
    "textures_plants": (4, 4.2),
    "icon_512": (8, 4.2),
    "icon_64": (6, 4.2),
}


def pixels(path):
    with open(path, "rb") as f:
        head = f.read(24)
    if head[:8] != b"\x89PNG\r\n\x1a\n":
        return None
    w, h = struct.unpack(">II", head[16:24])
    return w * h


def main():
    root = sys.argv[1]
    print("# QOI benchmark suite subset (https://qoiformat.org/benchmark/), generated by select_corpus.py")
    print("# sha256  path relative to images/; category: target count, pixel cap")
    for cat, (count, cap) in sorted(PLAN.items()):
        print(f"#   {cat}: {count}, {cap} MP")
    for cat, (count, cap) in sorted(PLAN.items()):
        d = os.path.join(root, cat)
        names = sorted(n for n in os.listdir(d) if n.endswith(".png"))
        ok = [n for n in names if (pixels(os.path.join(d, n)) or 1e18) <= cap * 1e6]
        step = max(1, len(ok) // count)
        for n in ok[::step][:count]:
            with open(os.path.join(d, n), "rb") as f:
                print(f"{hashlib.sha256(f.read()).hexdigest()}  {cat}/{n}")


main()
